/* MSM8974 platform shim: the Stage-owned replacement for XNU's ARM timer/interrupt init.
 *
 * Why a replacement and not a configuration
 * -----------------------------------------
 * `pe_arm_init_timer` (`external/xnu-4570.1.46/pexpert/arm/pe_identify_machine.c:589`) is a
 * chain of `#if defined(ARM_BOARD_CLASS_*)` tests on `gPESoCDeviceType`, ending in
 * `return 0`. The 32-bit ARM `pexpert/pexpert/arm/board_config.h` defines exactly three
 * classes - S7002, T8002 (for T8002 and T8004) - all Apple. **There is no configuration in
 * which the stock function succeeds on MSM8974**; it would need a board class that does not
 * exist. So this module replaces it, and in doing so it owns the four globals XNU's ARM code
 * reads (`gSocPhys`, `gPicBase`, `gTimerBase`, `gPESoCDeviceType`) and the `tbd_ops` it
 * registers through `ml_init_timebase`.
 *
 * See docs/status/phase3-msm8974-shim-spec.md for the full derivation. This file implements
 * section 2 (the interface) and section 3 (the hardware facts).
 *
 * The two decisions this file makes, and why
 * -----------------------------------------
 * 1. **CNTP, not CNTV.** XNU's `__ARM_TIME__` path uses the *virtual* timer, and states its
 *    reason in its own comment (`osfmk/arm/machine_routines_asm.s:924`): "for our current
 *    platforms, the interrupt generated by the physical timer is not hooked up to anything,
 *    and is therefore dropped on the floor." On MSM8974 that is measurably false - the
 *    payload armed CNTP and its interrupt arrived on intr 19 (experiment-12; spec section
 *    3.2). So the CNTV choice is a workaround for an Apple wiring decision this device does
 *    not share, and the shim points its decrementer callbacks at CNTP, reusing the measured
 *    interrupt number and the payload's validated timer code.
 *
 * 2. **The registration is verified, not assumed.** `ml_init_timebase` copies the ops only if
 *    `cpu_data_ptr == &BootCpuData` (`osfmk/arm/machine_routines.c:447`). Any other pointer
 *    makes the whole registration a silent no-op - no error, no log - and the failure then
 *    surfaces later as a clock or scheduling bug. This shim mirrors that guard exactly and
 *    then *reads the registration back* to confirm it took.
 *
 * 3. **No FIQ handler, and that is now a measured answer rather than an open question.**
 *    XNU's `locore.s:147` takes the `#else` branch (because `__ARM_TIME__` is undefined), so
 *    its timer arrives on **FIQ** on this build and `pe_arm_init_timer` supplies
 *    `fleh_fiq_generic` for it. The shim must therefore decide whether to supply
 *    `tbd_fiq_handler`, and the answer is **no** - measured on the device
 *    (`docs/experiments/experiment-143-fiq-not-available.md`): with intid 19 in GIC Group 0,
 *    Group 0 enabled at both ends, FIQ unmasked and the timer measurably fired
 *    (`fiq_timer_fired=1`), **no FIQ is taken** (`fiq_probe_fiq_delivered=0`). The vendor
 *    header's "FIQ requires secure mode" is true here.
 *
 *    **So the resolution is `__ARM_TIME__`** - the tree's complete IRQ path
 *    (`Lexc_decirq_vector` -> `fleh_decirq`, both real code) with the decrementer callbacks
 *    pointed at CNTP, which is decision 1 above and which the payload has already driven end
 *    to end (experiment-104: 10 ms asked for, 9961 us measured through the payload's own GIC
 *    IRQ path). The shim leaves `tbd_fiq_handler` NULL because a handler there **cannot be
 *    reached on this SoC**, not because it is unfinished.
 *
 * What is not claimed
 * -------------------
 * This does not run XNU. It is the platform layer XNU would need, written so that its
 * hardware facts are explicit, its registration contract is enforced, and it can be
 * exercised on the device by the existing payload.
 */

#include "stage90.h"

/*
 * --- The tbd_ops contract, mirrored ---------------------------------------------
 *
 * `osfmk/arm/machine_routines.h:242`:
 *
 *     struct tbd_ops {
 *             void     (*tbd_fiq_handler)(void);
 *             uint32_t (*tbd_get_decrementer)(void);
 *             void     (*tbd_set_decrementer)(uint32_t dec_value);
 *     };
 *
 * The layout matters for the same reason boot_args' did: XNU copies this struct by value
 * into a global and calls through it, so a field added or reordered here would be read as
 * whatever XNU expects at that offset. Mirrored exactly, and asserted.
 */
struct stage90_xnu_tbd_ops {
	void     (*tbd_fiq_handler)(void);
	uint32_t (*tbd_get_decrementer)(void);
	void     (*tbd_set_decrementer)(uint32_t dec_value);
};

_Static_assert(sizeof(struct stage90_xnu_tbd_ops) == 12u,
               "tbd_ops is three 32-bit pointers on ARM");
_Static_assert(offsetof(struct stage90_xnu_tbd_ops, tbd_fiq_handler) == 0u,
               "tbd_ops.tbd_fiq_handler at offset 0");
_Static_assert(offsetof(struct stage90_xnu_tbd_ops, tbd_get_decrementer) == 4u,
               "tbd_ops.tbd_get_decrementer at offset 4");
_Static_assert(offsetof(struct stage90_xnu_tbd_ops, tbd_set_decrementer) == 8u,
               "tbd_ops.tbd_set_decrementer at offset 8");

/*
 * --- The registered state, in the shape XNU keeps it ---------------------------
 *
 * XNU holds these as `RTClockData` members reached through `rtclock_timebase_func` /
 * `rtclock_timebase_addr` / `rtclock_timebase_val` (`osfmk/arm/rtclock.h:83-87`) and copies
 * them per-CPU in `cpu_timebase_init` (`osfmk/arm/cpu.c:458`). The shim keeps the same
 * three, so the same regis/consume relationship can be exercised.
 */
static struct stage90_xnu_tbd_ops g_registered_ops;
static uint32_t g_registered_int_address;
static uint32_t g_registered_int_value;
static uint32_t g_registered;   /* 1 once a registration has actually taken */

/* Mirrors XNU's `&BootCpuData` identity check: registration is a no-op unless the caller
 * passes the boot CPU's data. The shim has one CPU-data slot, and this is it. */
static uint32_t g_boot_cpu_data;
static uint32_t g_shadow_cpu_data;

/*
 * --- Hardware facts (spec section 3) ------------------------------------------
 */
#define MSM8974_GIC_DIST_BASE    0xf9000000u
#define MSM8974_GIC_CPU_BASE     0xf9002000u
/*
 * The SoC base XNU reads from /arm-io, and the timer block. Both are facts from the device tree
 * the payload builds (stage90_main.c: `io_ranges = {0, 0xf9000000, 0x07000000}`, `timer_reg[0] =
 * 0xf9020000`), not from a header - which is why they are named here with their source.
 */
#define MSM8974_SOC_PHYS         0xf9000000u
#define MSM8974_TIMER_BASE       0xf9020000u
#define MSM8974_GICC_IAR         (MSM8974_GIC_CPU_BASE + 0x00cu)
#define MSM8974_GICC_EOIR        (MSM8974_GIC_CPU_BASE + 0x010u)

/*
 * The ARM generic timer's *physical* timer arrives on intr 19 on this device, not the
 * architectural 30. Measured, not assumed: docs/experiments/experiment-12-stage9-timer-irq.md
 * shows the payload enabling PPIs 18 and 19, arming CNTP, and receiving IAR 0x13 with the
 * handler observing CNTP_CTL = 0x5 (enable + ISTATUS). Intr 18 was enabled alongside but
 * never observed to fire; the shim does not depend on it.
 */
#define MSM8974_TIMER_CNTP_INTID 19u

/* WDT_HZ and the watchdog are hw_watchdog.c's; the shim only needs the GIC and the timer. */

/* --- CNTP accessors: the shim's decrementer implementation -------------------- */

static inline uint32_t shim_read_cntp_tval(void)
{
	uint32_t v;
	__asm__ volatile ("mrc p15, 0, %0, c14, c2, 0" : "=r"(v));
	return v;
}

static inline void shim_write_cntp_tval(uint32_t v)
{
	__asm__ volatile ("mcr p15, 0, %0, c14, c2, 0" :: "r"(v) : "memory");
	__asm__ volatile ("isb" ::: "memory");
}

static inline uint32_t shim_read_cntp_ctl(void)
{
	uint32_t v;
	__asm__ volatile ("mrc p15, 0, %0, c14, c2, 1" : "=r"(v));
	return v;
}

static inline uint32_t shim_read_cntfrq(void)
{
	uint32_t v;
	__asm__ volatile ("mrc p15, 0, %0, c14, c0, 0" : "=r"(v));
	return v;
}

static inline void shim_mmio_write32(uint32_t addr, uint32_t value)
{
	*(volatile uint32_t *)(uintptr_t)addr = value;
}

static inline void shim_barrier(void)
{
	__asm__ volatile ("dsb sy\n\tisb" ::: "memory");
}

/*
 * The three tbd_ops callbacks.
 *
 * `get`/`set` are CNTP_TVAL, matching the counter the payload already drives and whose
 * interrupt number is measured. `tbd_fiq_handler` is deliberately NULL - see decision 3 above:
 * FIQ is measurably undeliverable here, so the timer's route is `__ARM_TIME__`'s IRQ path,
 * which is what these two callbacks serve. (Leaving it NULL also keeps XNU's registration
 * re-entrant, `ml_init_timebase`'s second condition, which costs nothing.)
 */
static uint32_t shim_get_decrementer(void)
{
	return shim_read_cntp_tval();
}

static void shim_set_decrementer(uint32_t dec_value)
{
	shim_write_cntp_tval(dec_value);
}

static struct stage90_xnu_tbd_ops g_shim_ops = {
	/*
	 * NULL because FIQ cannot be delivered to non-secure PL1 on this SoC - measured, not
	 * unfinished. See decision 3 in the file comment and experiment-143. A handler here would
	 * never be called; the resolution is __ARM_TIME__, which routes the timer through the IRQ
	 * path these two callbacks already serve.
	 */
	.tbd_fiq_handler = 0,
	.tbd_get_decrementer = shim_get_decrementer,
	.tbd_set_decrementer = shim_set_decrementer,
};

/* --- Result record ------------------------------------------------------------ */

static struct stage90_xnu_msm8974_shim_result g_result;

static uint32_t shim_checksum(const struct stage90_xnu_msm8974_shim_result *r)
{
	const uint32_t *words = (const uint32_t *)r;
	uint32_t count = (uint32_t)(offsetof(struct stage90_xnu_msm8974_shim_result, checksum) / sizeof(uint32_t));
	uint32_t chk = 0u;

	for (uint32_t i = 0u; i < count; i++) {
		chk ^= words[i];
	}
	return chk;
}

